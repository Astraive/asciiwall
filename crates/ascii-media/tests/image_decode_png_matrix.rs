fn limits() -> DecodeLimits {
    DecodeLimits::new(
        Budget::new(1 << 20, 1 << 20, 1 << 20),
        DecodeResources::new(4, 16 << 20),
        1024,
        1024,
        1 << 20,
        1 << 20,
    )
}

fn decode(bytes: &[u8]) -> Result<DecodedFrame, ascii_core::Error> {
    decode_image(
        &mut Cursor::new(bytes),
        &limits(),
        &CancellationToken::new(),
    )
}

fn assert_sha256(bytes: &[u8], expected: &str) {
    let actual = format!("{:x}", Sha256::digest(bytes));
    println!("png fixture sha256={actual}");
    assert_eq!(actual, expected);
}

#[test]
fn indexed_palette_trns_expands_to_rgba_with_per_entry_alpha() {
    assert_sha256(
        PALETTE_T_RNS_PNG,
        "0f8da7e103665d45988b85b8adaf7712285219589dc0c0859625044718592426",
    );

    let frame = decode(PALETTE_T_RNS_PNG).unwrap();
    assert_eq!(
        (frame.width(), frame.height(), frame.row_stride()),
        (3, 2, 12)
    );
    assert_eq!(frame.format().channels(), PixelChannels::Rgba);
    assert_eq!(frame.format().sample_depth_bits(), 8);
    assert_eq!(
        frame.pixels(),
        &[
            255, 0, 0, 0, 0, 255, 0, 127, 0, 0, 255, 255, 0, 0, 255, 255, 0, 255, 0, 127, 255, 0,
            0, 0,
        ],
    );
}

#[test]
fn adam7_rgba_preserves_dimensions_rows_and_alpha() {
    assert_sha256(
        ADAM7_RGBA_PNG,
        "3bb739db73a89dd1843b5b4630f2ba111d5d2a5f8f157c0caccff869d32e5dbd",
    );

    let frame = decode(ADAM7_RGBA_PNG).unwrap();
    assert_eq!(
        (frame.width(), frame.height(), frame.row_stride()),
        (9, 8, 36)
    );
    assert_eq!(frame.format().channels(), PixelChannels::Rgba);
    assert_eq!(frame.format().sample_depth_bits(), 8);

    let expected = (0..8u8)
        .flat_map(|y| {
            (0..9u8).flat_map(move |x| {
                let x = u16::from(x);
                let y = u16::from(y);
                [
                    (29 * x + 7 * y) as u8,
                    (31 * y + 3 * x) as u8,
                    (17 * u16::from((x as u8) ^ (y as u8))) as u8,
                    [0, 85, 170, 255][usize::from(((x + 2 * y) % 4) as u8)],
                ]
            })
        })
        .collect::<Vec<_>>();
    assert_eq!(frame.pixels(), expected);
}
